ROOT = Path(__file__).resolve().parent.parent
ALL_NAMES = [
    "server.crt", "server.key", "client.crt", "client.key",
    "client.next.crt", "client.next.key",
]
CERT_NAMES = [n for n in ALL_NAMES if n.endswith(".crt")]
KEY_NAMES = [n for n in ALL_NAMES if n.endswith(".key")]

needs_non_root = pytest.mark.skipif(
    hasattr(os, "geteuid") and os.geteuid() == 0, reason="root ignores file permissions"
)


def mode_of(path) -> int:
    return stat.S_IMODE(os.stat(path).st_mode)


def make_src(tmp_path: Path, *, next_identity=True, server=True) -> Path:
    """A real TLS directory (generated by `ensure_identity`) beside its 'database'."""
    (tmp_path / "config.db").touch()
    d = tmp_path / "config.db.tls"
    if server:
        identity.ensure_identity(d, "server")
    identity.ensure_identity(d, "client")
    if next_identity:
        identity.ensure_identity(d, "client", name="client.next")
    return d


@pytest.fixture
def src(tmp_path):
    return make_src(tmp_path)


@pytest.fixture
def dst(tmp_path):
    return tmp_path / "backup" / "tls"


@pytest.fixture
def backup_parent(tmp_path):
    (tmp_path / "backup").mkdir()
    return tmp_path / "backup"


def files_in(path: Path):
    return sorted(p.name for p in path.iterdir())


def pair_matches(d: Path, name: str) -> bool:
    """Do `<name>.crt` and `<name>.key` in `d` belong together?"""
    cert = x509.load_pem_x509_certificate((d / f"{name}.crt").read_bytes())
    key = serialization.load_pem_private_key((d / f"{name}.key").read_bytes(), None)
    spki = serialization.PublicFormat.SubjectPublicKeyInfo
    pem = serialization.Encoding.PEM
    return cert.public_key().public_bytes(pem, spki) == key.public_key().public_bytes(pem, spki)


def assert_consistent(d: Path) -> None:
    """Every identity present in `d` is a whole, matching pair."""
    for name in ("server", "client", "client.next"):
        crt, key = d / f"{name}.crt", d / f"{name}.key"
        assert crt.exists() == key.exists(), f"half a {name} pair in {d}: {files_in(d)}"
        if crt.exists():
            assert pair_matches(d, name), f"{name}.crt does not match {name}.key"


