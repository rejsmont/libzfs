@pytest.mark.integration
class TestConsistency:
    def test_a_copy_started_between_the_promotion_renames_waits_for_the_finished_pair(
        self, src, tmp_path, dst, backup_parent, helpers
    ):
        """Deterministic: a real process runs the real `promote_identity` and is
        held between its two renames (new key + old certificate on disk).
        `copy_tls_dir` must wait for the lock and then copy the PROMOTED pair --
        without the lock it would copy the mismatched key and certificate."""
        old_client_fp = identity.peek_identity(src, "client").fingerprint
        next_fp = identity.peek_identity(src, "client.next").fingerprint
        mid, release = tmp_path / "mid", tmp_path / "release"
        proc = helpers(start_helper(_PROMOTER_PAUSED_BETWEEN_THE_RENAMES, src, mid, release))
        wait_for(mid, proc)

        # The window is real: on disk right now, client.crt and client.key differ.
        assert not pair_matches(src, "client")

        result = {}

        def run():
            result["names"] = identity.copy_tls_dir(src, dst, lock_timeout=30)

        t = threading.Thread(target=run)
        t.start()
        try:
            time.sleep(0.4)
            assert t.is_alive(), "the copy did not wait for the promotion to finish"
        finally:
            release.touch()
            t.join(30)
        out, err = proc.communicate(timeout=30)
        assert proc.returncode == 0, out + err
        assert not t.is_alive()

        assert_consistent(dst)
        assert pair_matches(dst, "client")
        assert identity.peek_identity(dst, "client").fingerprint == next_fp
        assert next_fp != old_client_fp
        assert "client.next.crt" not in result["names"] and "client.next.key" not in result["names"]

    def test_a_copy_never_sees_a_half_or_mismatched_pair_under_continuous_rotation(
        self, src, tmp_path, backup_parent, helpers
    ):
        stop = tmp_path / "stop"
        proc = helpers(start_helper(_CYCLER, src, stop))
        copies = 0
        deadline = time.monotonic() + 3.0
        try:
            while time.monotonic() < deadline or copies < 15:
                if proc.poll() is not None:
                    break
                target = backup_parent / f"copy-{copies}"
                identity.copy_tls_dir(src, target, lock_timeout=30)
                assert_consistent(target)
                copies += 1
        finally:
            stop.touch()
        out, err = proc.communicate(timeout=60)
        assert proc.returncode == 0, out + err
        assert int(out.strip()) >= 5, "the writer barely ran; the test proved nothing"
        assert copies >= 15
