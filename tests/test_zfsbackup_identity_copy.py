@pytest.mark.unit
class TestDestination:
    def test_a_new_destination_is_0700(self, src, dst, backup_parent):
        old = os.umask(0o000)
        try:
            identity.copy_tls_dir(src, dst)
        finally:
            os.umask(old)
        assert mode_of(dst) == 0o700

    def test_an_existing_directory_is_set_to_0700_and_kept(self, src, dst, backup_parent):
        dst.mkdir()
        os.chmod(dst, 0o755)
        (dst / "unrelated").write_text("mine")
        identity.copy_tls_dir(src, dst)
        assert mode_of(dst) == 0o700
        assert (dst / "unrelated").read_text() == "mine"

    def test_the_parent_must_exist(self, src, dst):
        with pytest.raises(identity.IdentityError, match="cannot create"):
            identity.copy_tls_dir(src, dst)
        assert not dst.parent.exists()

    def test_a_symlinked_destination_is_refused_and_its_target_untouched(
        self, src, dst, backup_parent, tmp_path
    ):
        target = tmp_path / "elsewhere"
        target.mkdir()
        dst.symlink_to(target)
        with pytest.raises(identity.IdentityError):
            identity.copy_tls_dir(src, dst)
        assert files_in(target) == []
        assert dst.is_symlink()

    def test_a_destination_that_is_a_file_is_refused(self, src, dst, backup_parent):
        dst.write_text("a file")
        with pytest.raises(identity.IdentityError):
            identity.copy_tls_dir(src, dst)
        assert dst.read_text() == "a file"

    @pytest.mark.parametrize("existing", ALL_NAMES)
    def test_an_existing_file_is_never_overwritten(self, src, dst, backup_parent, existing):
        dst.mkdir()
        (dst / existing).write_text("precious")
        with pytest.raises(identity.IdentityError, match="already exists; not overwriting"):
            identity.copy_tls_dir(src, dst)
        assert (dst / existing).read_text() == "precious"

    @pytest.mark.parametrize("existing", ["server.crt", "client.key", "client.next.key"])
    def test_a_refusal_removes_what_this_call_had_already_written(
        self, src, dst, backup_parent, existing
    ):
        """The directory pre-exists, so it stays; the files this call made go,
        the file that was there before stays exactly as it was."""
        dst.mkdir()
        (dst / existing).write_text("precious")
        with pytest.raises(identity.IdentityError):
            identity.copy_tls_dir(src, dst)
        assert files_in(dst) == [existing]
        assert (dst / existing).read_text() == "precious"

    def test_a_second_copy_into_the_same_directory_is_refused(self, src, dst, backup_parent):
        identity.copy_tls_dir(src, dst)
        before = {n: (dst / n).read_bytes() for n in files_in(dst)}
        with pytest.raises(identity.IdentityError, match="already exists"):
            identity.copy_tls_dir(src, dst)
        assert {n: (dst / n).read_bytes() for n in files_in(dst)} == before

    def test_a_write_failure_removes_the_files_and_the_directory_it_created(
        self, src, dst, backup_parent, mocker
    ):
        real = identity._write_all
        calls = []

        def flaky(fd, data):
            calls.append(1)
            if len(calls) == 3:
                raise OSError(errno.ENOSPC, "No space left on device")
            return real(fd, data)

        mocker.patch.object(identity, "_write_all", side_effect=flaky)
        with pytest.raises(identity.IdentityError, match="cannot write"):
            identity.copy_tls_dir(src, dst)
        assert len(calls) == 3
        assert not dst.exists()

    def test_a_write_failure_into_an_existing_directory_leaves_it_as_it_was(
        self, src, dst, backup_parent, mocker
    ):
        dst.mkdir()
        (dst / "unrelated").write_text("mine")
        real = identity._write_all
        calls = []

        def flaky(fd, data):
            calls.append(1)
            if len(calls) == 2:
                raise OSError(errno.EIO, "I/O error")
            return real(fd, data)

        mocker.patch.object(identity, "_write_all", side_effect=flaky)
        with pytest.raises(identity.IdentityError):
            identity.copy_tls_dir(src, dst)
        assert files_in(dst) == ["unrelated"]

    def test_a_non_oserror_during_the_write_also_cleans_up(self, src, dst, backup_parent, mocker):
        mocker.patch.object(identity, "_write_all", side_effect=KeyboardInterrupt)
        with pytest.raises(KeyboardInterrupt):
            identity.copy_tls_dir(src, dst)
        assert not dst.exists()


