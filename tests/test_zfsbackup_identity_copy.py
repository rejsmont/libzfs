"""Milestone C, item C4: `identity.copy_tls_dir` and `identity.KeyUnreadable`.

`copy_tls_dir(src, dst, *, include_keys=True, lock_timeout=30.0)` takes a
consistent snapshot of a TLS directory (`server.*`, `client.*`,
`client.next.*`) for the backup command. What must hold:

- ``TestCopiedFiles``        which files, their modes whatever the umask, verbatim
  content, the order, no `identity.lock` or temporaries, an absent
  `client.next` pair.
- ``TestDestination``        created 0700 / existing set to 0700, a missing
  parent, a symlinked destination, overwrite refusal, cleanup after a failure.
- ``TestKeys``               `KeyUnreadable` is a `PermissionError` naming the
  key and nothing has been created; `include_keys=False` never opens a key.
- ``TestSource``             a missing, symlinked or non-directory `src` is an
  `IdentityError` with nothing created.
- ``TestLocking``            the lock is taken SHARED (opened read-only, never
  created) so the daemon's own readers are not held up, a writer's exclusive
  hold makes the copy wait or time out cleanly, an unopenable lock is an
  `IdentityError`, a missing `identity.lock` means an unlocked read that is
  re-checked and redone under the lock if one appeared meanwhile.
- ``TestConsistency``        real processes taking `identity.lock`: a copy
  started while `promote_identity` sits between its two renames waits and gets
  the finished pair; a stress loop of promotions against copies never yields a
  mismatched or half pair.

Hermetic: no `zfs`, no sockets; every helper process is killed in a `finally`.

Mutation-checked (scratch copy of ``zfsbackup/``), tests failing:

- no locking at all (the shared-lock read skipped, and the unlocked path's
  re-check disabled): 11 (nine in `TestLocking`, the deterministic
  between-the-renames window test, and the rotation stress test);
- only the re-check after an unlocked read disabled: 2 (the two
  lock-appears-meanwhile tests in `TestLocking`).
"""

