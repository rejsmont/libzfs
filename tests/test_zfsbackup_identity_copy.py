@pytest.mark.unit
class TestSource:
    def test_a_missing_source(self, tmp_path, dst, backup_parent):
        with pytest.raises(identity.IdentityError, match="does not exist"):
            identity.copy_tls_dir(tmp_path / "nope.tls", dst)
        assert not dst.exists()

    def test_a_symlinked_source_is_refused(self, src, tmp_path, dst, backup_parent):
        link = tmp_path / "link.tls"
        link.symlink_to(src)
        with pytest.raises(identity.IdentityError, match="symlink or not a directory"):
            identity.copy_tls_dir(link, dst)
        assert not dst.exists()

    def test_a_source_that_is_a_file(self, tmp_path, dst, backup_parent):
        f = tmp_path / "file.tls"
        f.write_text("x")
        with pytest.raises(identity.IdentityError, match="symlink or not a directory"):
            identity.copy_tls_dir(f, dst)
        assert not dst.exists()

    def test_a_symlinked_file_inside_the_source_is_followed_like_everywhere_else(
        self, src, tmp_path, dst, backup_parent
    ):
        """Operator-supplied key and certificate paths may legitimately be
        links (`_read_file` follows them); the symlink refusal is for the
        directory itself. The copy is a regular file."""
        real_cert = tmp_path / "real-server.crt"
        real_cert.write_bytes((src / "server.crt").read_bytes())
        (src / "server.crt").unlink()
        (src / "server.crt").symlink_to(real_cert)
        identity.copy_tls_dir(src, dst)
        assert not (dst / "server.crt").is_symlink()
        assert (dst / "server.crt").read_bytes() == real_cert.read_bytes()


