@pytest.mark.unit
class TestCopiedFiles:
    def test_public_names_are_exported(self):
        assert "copy_tls_dir" in identity.__all__ and "KeyUnreadable" in identity.__all__

    def test_all_six_files_are_copied_and_named_in_the_return(self, src, dst, backup_parent):
        assert identity.copy_tls_dir(src, dst) == ALL_NAMES
        assert files_in(dst) == sorted(ALL_NAMES)

    def test_contents_are_verbatim(self, src, dst, backup_parent):
        identity.copy_tls_dir(src, dst)
        for name in ALL_NAMES:
            assert (dst / name).read_bytes() == (src / name).read_bytes()

    def test_contents_are_not_parsed(self, src, dst, backup_parent):
        (src / "server.crt").write_bytes(b"not a certificate\n\x00\xff")
        identity.copy_tls_dir(src, dst)
        assert (dst / "server.crt").read_bytes() == b"not a certificate\n\x00\xff"

    @pytest.mark.parametrize("umask", [0o000, 0o077, 0o022])
    def test_modes_are_exact_whatever_the_umask(self, src, dst, backup_parent, umask):
        old = os.umask(umask)
        try:
            identity.copy_tls_dir(src, dst)
        finally:
            os.umask(old)
        assert mode_of(dst) == 0o700
        for name in KEY_NAMES:
            assert mode_of(dst / name) == 0o600, name
        for name in CERT_NAMES:
            assert mode_of(dst / name) == 0o640, name

    def test_the_lock_file_and_temporaries_are_not_copied(self, src, dst, backup_parent):
        assert (src / "identity.lock").exists()
        (src / ".client.crt.tmp").write_text("half written")
        (src / "notes.txt").write_text("stray")
        names = identity.copy_tls_dir(src, dst)
        assert "identity.lock" not in names
        assert files_in(dst) == sorted(ALL_NAMES)

    def test_a_missing_client_next_pair_is_simply_absent(self, tmp_path, dst, backup_parent):
        src = make_src(tmp_path, next_identity=False)
        assert identity.copy_tls_dir(src, dst) == [
            "server.crt", "server.key", "client.crt", "client.key",
        ]
        assert files_in(dst) == ["client.crt", "client.key", "server.crt", "server.key"]

    def test_a_directory_with_only_a_server_identity(self, tmp_path, dst, backup_parent):
        (tmp_path / "config.db").touch()
        src = tmp_path / "config.db.tls"
        identity.ensure_identity(src, "server")
        assert identity.copy_tls_dir(src, dst) == ["server.crt", "server.key"]

    def test_an_empty_directory_copies_nothing_and_still_makes_the_destination(
        self, tmp_path, dst, backup_parent
    ):
        src = tmp_path / "empty.tls"
        src.mkdir()
        assert identity.copy_tls_dir(src, dst) == []
        assert dst.is_dir() and files_in(dst) == []

    def test_the_source_is_left_untouched(self, src, dst, backup_parent):
        before = {n: ((src / n).read_bytes(), mode_of(src / n)) for n in files_in(src)}
        identity.copy_tls_dir(src, dst)
        assert {n: ((src / n).read_bytes(), mode_of(src / n)) for n in files_in(src)} == before

    def test_the_copy_is_loadable(self, src, dst, backup_parent):
        identity.copy_tls_dir(src, dst)
        for name in ("server", "client", "client.next"):
            role = "server" if name == "server" else "client"
            copied = identity.load_identity(dst / f"{name}.crt", dst / f"{name}.key", role)
            original = identity.load_identity(src / f"{name}.crt", src / f"{name}.key", role)
            assert copied.fingerprint == original.fingerprint

    def test_str_paths_are_accepted(self, src, dst, backup_parent):
        assert identity.copy_tls_dir(str(src), str(dst)) == ALL_NAMES

    def test_the_options_are_keyword_only(self, src, dst, backup_parent):
        with pytest.raises(TypeError):
            identity.copy_tls_dir(src, dst, False)


