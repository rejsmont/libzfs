@pytest.mark.unit
class TestKeys:
    def test_key_unreadable_is_a_permission_error(self):
        exc = identity.KeyUnreadable("/x/client.key")
        assert isinstance(exc, PermissionError) and isinstance(exc, OSError)
        assert exc.errno == errno.EACCES
        assert exc.filename == "/x/client.key"
        assert "private key" in str(exc)

    def test_key_unreadable_accepts_a_path(self):
        assert identity.KeyUnreadable(Path("/x/server.key")).filename == "/x/server.key"

    @needs_non_root
    @pytest.mark.parametrize("key", KEY_NAMES)
    def test_an_unreadable_key_raises_key_unreadable_naming_it(self, src, dst, backup_parent, key):
        os.chmod(src / key, 0)
        try:
            with pytest.raises(identity.KeyUnreadable) as exc:
                identity.copy_tls_dir(src, dst)
        finally:
            os.chmod(src / key, 0o600)
        assert Path(exc.value.filename) == src / key
        assert not dst.exists()

    @needs_non_root
    def test_nothing_is_created_not_even_for_keys_after_the_unreadable_one(
        self, src, dst, backup_parent
    ):
        """The unreadable key is the LAST file; the certificates before it
        were already read, yet nothing may exist at the destination."""
        os.chmod(src / "client.next.key", 0)
        try:
            with pytest.raises(identity.KeyUnreadable):
                identity.copy_tls_dir(src, dst)
        finally:
            os.chmod(src / "client.next.key", 0o600)
        assert not dst.exists()

    @needs_non_root
    def test_an_existing_destination_is_not_touched_either(self, src, dst, backup_parent):
        dst.mkdir()
        os.chmod(dst, 0o755)
        os.chmod(src / "server.key", 0)
        try:
            with pytest.raises(identity.KeyUnreadable):
                identity.copy_tls_dir(src, dst)
        finally:
            os.chmod(src / "server.key", 0o600)
        assert files_in(dst) == [] and mode_of(dst) == 0o755

    def test_a_denied_key_read_is_mapped_even_when_running_as_root(self, src, dst, backup_parent, mocker):
        """`_read_file` raising its permission-denied error for a `.key` is the
        mapping under test; no file mode is involved."""
        real = identity._read_file

        def deny_keys(path, what):
            if str(path).endswith(".key"):
                raise identity._AccessDenied(f"cannot read {what} {path}", path)
            return real(path, what)

        mocker.patch.object(identity, "_read_file", side_effect=deny_keys)
        with pytest.raises(identity.KeyUnreadable) as exc:
            identity.copy_tls_dir(src, dst)
        assert Path(exc.value.filename).name == "server.key"      # the first key it reached
        assert not dst.exists()

    def test_an_unreadable_certificate_is_an_identity_error_not_key_unreadable(
        self, src, dst, backup_parent, mocker
    ):
        real = identity._read_file

        def deny_certs(path, what):
            if str(path).endswith("client.crt"):
                raise identity._AccessDenied(f"cannot read {what} {path}", path)
            return real(path, what)

        mocker.patch.object(identity, "_read_file", side_effect=deny_certs)
        with pytest.raises(identity.IdentityError) as exc:
            identity.copy_tls_dir(src, dst)
        assert not isinstance(exc.value, identity.KeyUnreadable)
        assert not dst.exists()

    @needs_non_root
    def test_include_keys_false_copies_the_certificates_and_survives_unreadable_keys(
        self, src, dst, backup_parent
    ):
        for key in KEY_NAMES:
            os.chmod(src / key, 0)
        try:
            assert identity.copy_tls_dir(src, dst, include_keys=False) == CERT_NAMES
        finally:
            for key in KEY_NAMES:
                os.chmod(src / key, 0o600)
        assert files_in(dst) == sorted(CERT_NAMES)
        for name in CERT_NAMES:
            assert (dst / name).read_bytes() == (src / name).read_bytes()
            assert mode_of(dst / name) == 0o640

    def test_include_keys_false_never_opens_a_key(self, src, dst, backup_parent, mocker):
        opened = []
        real = identity._read_file

        def spy(path, what):
            opened.append(Path(path).name)
            return real(path, what)

        mocker.patch.object(identity, "_read_file", side_effect=spy)
        identity.copy_tls_dir(src, dst, include_keys=False)
        assert opened and not [n for n in opened if n.endswith(".key")]

    def test_include_keys_true_reads_every_key(self, src, dst, backup_parent, mocker):
        opened = []
        real = identity._read_file
        mocker.patch.object(
            identity, "_read_file",
            side_effect=lambda p, w: (opened.append(Path(p).name), real(p, w))[1],
        )
        identity.copy_tls_dir(src, dst)
        assert sorted(opened) == sorted(ALL_NAMES)


