_PROMOTER_PAUSED_BETWEEN_THE_RENAMES = textwrap.dedent(
    """
    import os, sys, time
    from pathlib import Path
    from zfsbackup import identity

    d, mid, release = sys.argv[1:4]
    real = identity._fsync_dir
    state = {"n": 0}

    def paused(dir_fd, directory):
        real(dir_fd, directory)
        state["n"] += 1
        if state["n"] == 1:
            # The key has been renamed over client.key; the certificate has not.
            Path(mid).touch()
            deadline = time.monotonic() + 60
            while not os.path.exists(release) and time.monotonic() < deadline:
                time.sleep(0.01)

    identity._fsync_dir = paused
    identity.promote_identity(d)
    """
)

