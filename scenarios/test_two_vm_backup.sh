# mint_token [trust token create args...]  — on the SERVER; sets TOKEN (a secret: never echoed) and TOKEN_FP
# (the server certificate fingerprint the token carries). Returns 1 if the CLI did not print both.
TOKEN=""; TOKEN_FP=""
mint_token() {
    local out
    TOKEN=""; TOKEN_FP=""
    out="$(cli_out "$SERVER_VM" trust token create --json "$@")" || return 1
    TOKEN="$(printf '%s\n' "$out" | sed -n 's/^ *"token": *"\([^"]*\)".*/\1/p' | head -n1)"
    TOKEN_FP="$(printf '%s\n' "$out" | sed -n 's/^ *"server_fingerprint": *"\([^"]*\)".*/\1/p' | head -n1)"
    [ -n "$TOKEN" ] && [ -n "$TOKEN_FP" ]
}
# put_token <vm> <guest-path>  — the current $TOKEN as a root-owned 0600 FILE on <vm>. It goes through a 0600 host
# temp file and `multipass transfer` (never a command line, never piped stdin).
put_token() {
    local vm="$1" dst="$2" tmp
    tmp="$(mktemp)" && chmod 600 "$tmp" || return 1
    printf '%s\n' "$TOKEN" > "$tmp"
    multipass transfer "$tmp" "$vm:/tmp/zfsb-token.$$" || { rm -f "$tmp"; return 1; }
    rm -f "$tmp"
    msh "$vm" "install -m600 -o root -g root '/tmp/zfsb-token.$$' '$dst' && rm -f '/tmp/zfsb-token.$$'"
}
# enroll_client — the operator's path: an unscoped token minted on the server, shipped as a file, and
# `enroll $DEST_NAME --url https://<server-ip>:<port> --token-file ...` on the client (root: the TLS dir is root-owned
# 0750). Sets CLIENT_ID (generated by enroll, read back from `identity show --json`), SERVER_FP and PIN_FP. die()s on
# failure: nothing after it makes sense without an enrolled client.
enroll_client() {
    local out rc
    step "Enrolling $CLIENT_VM at https://${SERVER_IP}:${API_PORT} (token from $SERVER_VM)"
    mint_token || die "could not create an enrollment token on $SERVER_VM (multipass exec $SERVER_VM -- sudo tail $LOG)"
    put_token "$CLIENT_VM" /tmp/zfsb-token || die "could not deliver the token file to $CLIENT_VM"
    out="$(cli_vm "$CLIENT_VM" enroll "$DEST_NAME" --url "https://${SERVER_IP}:${API_PORT}" --token-file /tmp/zfsb-token)"; rc=$?
    msh "$CLIENT_VM" "rm -f /tmp/zfsb-token" || true
    printf '%s\n' "$out" | sed 's/^/    CLI: /'
    [ "$rc" -eq 0 ] || die "enroll failed (exit $rc)"
    CLIENT_ID="$(client_id_now)"
    [ -n "$CLIENT_ID" ] || die "enroll succeeded but 'identity show' reports no client id"
    SERVER_FP="$TOKEN_FP"; PIN_FP="$TOKEN_FP"
    info "enrolled: client_id=$CLIENT_ID  server fingerprint=$SERVER_FP"
}

# Authenticated (or not) HTTPS probes from the client VM with curl: probe <cert-base|none> <METHOD> <path> [json body].
# <cert-base> is the path without .crt/.key. Prints the HTTP status ("000" if the TLS handshake itself failed); the
# body is left in /tmp/zfsb-probe.json in the guest (probe_body). -k: curl cannot check our pin, zfsbackup's client does.
probe() {
    local cert="$1" method="$2" path="$3" body="${4:-}" certargs="" dataargs=""
    [ "$cert" != none ] && certargs="--cert '${cert}.crt' --key '${cert}.key'"
    [ -n "$body" ] && dataargs="-H 'Content-Type: application/json' --data '$body'"
    # X-Zfsbackup-Protocol: every request names the wire protocol (plan S-5); without it an authenticated request is 426.
    msh "$CLIENT_VM" "rm -f /tmp/zfsb-probe.json; curl -sk --connect-timeout 5 --max-time 20 -H 'X-Zfsbackup-Protocol: 1' $certargs -X $method $dataargs -o /tmp/zfsb-probe.json -w '%{http_code}' 'https://${SERVER_IP}:${API_PORT}${path}'" | tr -d '[:space:]'
}
probe_body() { msh "$CLIENT_VM" "cat /tmp/zfsb-probe.json 2>/dev/null"; }

# check_has "<description>" "<ERE>" "<text>" / check_lacks — pass when the text does / does not match
check_has() {
    if printf '%s' "$3" | grep -qE -- "$2"; then pass "$1"; else
        fail "$1 (no match for /$2/ in: $(printf '%s' "$3" | tr '\n' '|' | cut -c1-300))"
    fi
}
check_lacks() {
    if printf '%s' "$3" | grep -qE -- "$2"; then
        fail "$1 (unexpected /$2/ in: $(printf '%s' "$3" | tr '\n' '|' | cut -c1-300))"
    else pass "$1"; fi
}

