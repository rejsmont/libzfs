# ═════════════════════ TLS enrollment helpers (used by every scenario that needs a client id) ═════════════════════
put_guest_file() { # put_guest_file <vm> <guest-path>   (content on stdin; via multipass transfer, never piped exec)
    local vm="$1" dst="$2" tmp; tmp="$(mktemp)"; cat > "$tmp"
    multipass transfer "$tmp" "$vm:/tmp/zfsb-xfer.$$" || die "transfer to $vm:$dst failed"
    msh "$vm" "install -D -m644 /tmp/zfsb-xfer.$$ '$dst' && rm -f /tmp/zfsb-xfer.$$" || die "install of $dst failed on $vm"
    rm -f "$tmp"
}
# jget.py: reads JSON on stdin and prints the python expression given as argv[1], evaluated with the parsed
# value bound to `d` (None prints as an empty string). The expressions are written by this harness, never
# taken from a VM. This is how the harness reads `--json` output without needing jq or host-side parsing.
put_jget() { # put_jget <vm>
    put_guest_file "$1" "$JGET_PY" <<'PYEOF'
import json, sys
d = json.load(sys.stdin)
v = eval(sys.argv[1], {"d": d})
print("" if v is None else v)
PYEOF
}

