cli_out() { local vm="$1"; shift; msh "$vm" "env PYTHONPATH='$SRC_DIR' '$PY' -m zfsbackup.cli -c '$DB' $* 2>/dev/null"; }
# cli_jget_db <vm> <db> '<python expr over d>' <cli args...>  — print the expression over the command's JSON output
