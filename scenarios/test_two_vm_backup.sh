    mint_token || die "(K2) could not create a token on $SERVER_VM"
    put_token "$CLIENT_VM" /tmp/zfsb-token-t1 || die "(K2) could not deliver the token file"
    out="$(cli_vm "$CLIENT_VM" enroll "$DEST_NAME" --url "https://${SERVER_IP}:${API_PORT}" --token-file /tmp/zfsb-token-t1)"; rc=$?
    printf '%s\n' "$out" | sed 's/^/    CLI: /'
    check "(K2) enroll A exits 0" "0" "$rc"
    check_has "(K2) the CLI reports client id $K_ID (enroll reuses the id set in K1b)" "enrolled destination '${DEST_NAME}'.*as client id ${K_ID}" "$out"
    SERVER_FP="$TOKEN_FP"; PIN_FP="$TOKEN_FP"; CLIENT_ID="$(client_id_now)"
    check "(K2) the client id is unchanged by enroll" "$K_ID" "$CLIENT_ID"
    A_FP="$(client_fp)"
    check "(K2) A's destination is pinned to the server fingerprint from the token" "$SERVER_FP" \
        "$(cli_jget "$CLIENT_VM" 'd[0]["server_fingerprint"]' list destinations --json | tr -d '[:space:]')"
    check "(K2) the server pins exactly A's certificate" "$A_FP -" "$(trust_pins "$K_ID")"
    check "(K2) the token is now consumed, by A" "consumed $K_ID" \
        "$(cli_jget "$SERVER_VM" 'd["state"] + " " + str(d["consumed_client_id"])' trust token show --json | tr -d '\r')"
    check_has "(K2) positive control: the server logs requests (POST /enroll)" 'POST /enroll HTTP/1\.1' "$(log_since_vm "$SERVER_VM" "$mark_s")"
    if wait_server_snap "$K_S0" 150; then pass "(K2) the running daemon picked up the enrollment and sent the baseline $K_S0"; else fail "(K2) $K_S0 never reached the server"; fi
    wait_log_vm "$CLIENT_VM" "$mark_c" "Backup complete: ${SOURCE_DS}@${K_S0} \(full\)" 30 \
        && pass "(K2) log: Backup complete (full) for the baseline" || fail "(K2) no 'Backup complete: ${SOURCE_DS}@${K_S0} (full)'"
    check "(K2) the baseline is byte-identical on the server" "$(guid "$CLIENT_VM" "${SOURCE_DS}@${K_S0}")" "$(guid "$SERVER_VM" "$(server_ds)@${K_S0}")"
    # B: its own DB, its own certificate, the SAME (now spent) token file
    put_config_b
    mark_s="$(loglines "$SERVER_VM")"
    out="$(cli_b enroll "$DEST_NAME" --url "https://${SERVER_IP}:${API_PORT}" --token-file /tmp/zfsb-token-t1)"; rc=$?
    printf '%s\n' "$out" | sed 's/^/    CLI(B): /'
    check "(K2) B with the consumed token: exit 1" "1" "$rc"
    check_has "(K2) B is told the token is refused" "refused the token" "$out"
    check_lacks "(K2) the token text is not echoed" "zfsb1\." "$out"
    check "(K2) the server still trusts exactly one client (A)" "1" "$(cli_jget "$SERVER_VM" 'len(d)' trust list --json | tr -d '[:space:]')"
    check "(K2) B has no pinned server (its destination stays un-enrolled)" "" \
        "$(cli_jget_db "$CLIENT_VM" "$K_DB_B" '",".join(e["name"] for e in d if e["server_fingerprint"])' list destinations --json | tr -d '[:space:]')"

    # ── K3: an unscoped token naming a known id ──
    echo
    step "K3 — an UNSCOPED token that names an id the server already knows: 409 client_id_taken (exit 1, hint), and the token stays usable"
    out="$(cli_b identity set-client-id "$K_ID")"; rc=$?
    check "(K3) B takes A's id locally (nothing is enrolled in B's DB)" "0" "$rc"
    mint_token || die "(K3) could not create a token"
    put_token "$CLIENT_VM" /tmp/zfsb-token-t2 || die "(K3) could not deliver the token file"
    out="$(cli_b enroll "$DEST_NAME" --url "https://${SERVER_IP}:${API_PORT}" --token-file /tmp/zfsb-token-t2)"; rc=$?
    printf '%s\n' "$out" | sed 's/^/    CLI(B): /'
    check "(K3) B enrolling as A's id: exit 1" "1" "$rc"
    check_has "(K3) the CLI says the server already knows the id" "already knows a client with id '${K_ID}'" "$out"
    check_has "(K3) ... and tells the operator what to do (trust token create --client-id)" "trust token create --client-id ${K_ID}" "$out"
    check_has "(K3) ... and that the token was not used" "token was not used and is still valid" "$out"
    check "(K3) the token is still ACTIVE on the server" "active" "$(cli_jget "$SERVER_VM" 'd["state"]' trust token show --json | tr -d '[:space:]')"
    check "(K3) A still has exactly its one pin; no second client" "1 $A_FP -" \
