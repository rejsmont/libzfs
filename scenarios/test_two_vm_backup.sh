# straight after the handshake, which the client words differently)
K_REFUSED_RE="does not trust this client|may have rejected this client's certificate"
K_DB_B="/var/lib/zfsbackup-b/config.db"
K_TLS_B="${K_DB_B}.tls"
cli_b() { cli_dbvm "$CLIENT_VM" "$K_DB_B" "$@"; }
# B's DB: a disabled placeholder dataset (the loader wants a non-empty list) and the destination, NOT pinned.
put_config_b() {
    msh "$CLIENT_VM" "mkdir -p /var/lib/zfsbackup-b" || die "could not create /var/lib/zfsbackup-b"
    put_guest_file "$CLIENT_VM" /var/lib/zfsbackup-b/config.yaml <<EOF
snapshot_prefix: "autosnap"
check_interval: "1m"
destinations:
  ${DEST_NAME}:
    url: "https://${SERVER_IP}:${API_PORT}"
datasets:
  - name: "${SOURCE_DS}"
    enabled: false
    frequency: "1h"
    retention:
      "1h": "1d"
EOF
    cli_b import --no-backup /var/lib/zfsbackup-b/config.yaml | sed 's/^/    CLI(B): /'
}
# What a refused client must NOT cause: a send, a request on the server, a dataset under the target.
k_nothing_sent() { # k_nothing_sent <label> <client log mark> <server log mark>
    check "($1) no zfs send ran on the client" "0" "$(log_since_vm "$CLIENT_VM" "$2" | grep -cE 'Sending (incremental|full)')"
    check "($1) the server saw no HTTP request from the client" "0" "$(log_since_vm "$SERVER_VM" "$3" | grep -cE 'HTTP/1\.1[^"]*"')"
    check "($1) the server holds no client data under $TARGET_DS" "1" \
        "$(msh "$SERVER_VM" "zfs list -H -r -o name '$TARGET_DS' | wc -l" | tr -d '[:space:]')"
}

