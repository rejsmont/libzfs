PIP="${VENV}/bin/pip"
CFG="/etc/zfsbackup/config.yaml"         # YAML import input (the daemon no longer reads YAML)
DB="/var/lib/zfsbackup/config.db"        # SQLite config DB the daemon actually reads
TLS_DIR="${DB}.tls"                      # <db>.tls: server.{crt,key} / client.{crt,key}, identity.lock (root-owned 0750)
JGET_PY="/opt/zfsb-jget.py"              # reads JSON on stdin, prints a python expression over it (see put_jget)
LOG="/var/log/zfsbackup.log"
