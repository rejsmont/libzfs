    wait_health || die "(K) server API never became healthy"
    kmark_c="$(loglines "$CLIENT_VM")"; kmark_s="$(loglines "$SERVER_VM")"    # (the logs are append-only across scenarios)
    K_S0="$(snap_now)"

    # ── K1: not enrolled ──
    echo
    step "K1 — a client that is not enrolled is refused: first with no client id, then with an id but no pinned server"
    mark_c="$(loglines "$CLIENT_VM")"; mark_s="$(loglines "$SERVER_VM")"
    start_daemon "$CLIENT_VM"
