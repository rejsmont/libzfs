        K5_NEXT="$(snap_now)"
        if wait_log_vm "$CLIENT_VM" "$mark_k5" "ERROR.*(${K_REFUSED_RE})" 150; then
            pass "(K5) the next cycle is refused: ERROR 'does not trust this client'"
            show_log "$CLIENT_VM" "$mark_k5" "$K_REFUSED_RE"
        else fail "(K5) no 'does not trust this client' ERROR after the revoke: $(log_since_vm "$CLIENT_VM" "$mark_k5" | tail -n 5 | tr '\n' '|')"; fi
        sleep 40     # another remote cycle or two: the refusal is logged once and nothing is sent
        check "(K5) the refusal was logged once" "1" "$(log_since_vm "$CLIENT_VM" "$mark_k5" | grep -cE "ERROR.*(${K_REFUSED_RE})")"
        check "(K5) no zfs send ran after the revoke" "0" "$(log_since_vm "$CLIENT_VM" "$mark_k5" | grep -cE 'Sending (incremental|full)')"
        check "(K5) no further 'Backup complete'" "0" "$(log_since_vm "$CLIENT_VM" "$mark_k5" | grep -c 'Backup complete')"
        check "(K5) no /backup/ request reached the server after the revoke" "0" "$(log_since_vm "$SERVER_VM" "$mark_k5s" | grep -c '/backup/')"
        check "(K5) the pending snapshot $K5_NEXT is not on the server" "no" "$(server_snaps | grep -qx "$K5_NEXT" && echo yes || echo no)"
        check "(K5) the client's anchor stayed at $K5_SNAP" "$K5_SNAP" "$(anchor)"
    fi

    # ── K6: re-enroll under the same id with a new certificate ──
    echo
    step "K6 — re-enroll with a --client-id $K_ID --replace token and a NEW certificate: same id, same server dataset, INCREMENTAL"
    stop_daemon "$CLIENT_VM"
    mint_token --client-id "$K_ID" --replace || die "(K6) could not create a scoped token"
    put_token "$CLIENT_VM" /tmp/zfsb-token-t3 || die "(K6) could not deliver the token file"
    # a new certificate: `enroll --new-key` generates client.next, enrolls it with the token, then promotes it
    # (the revoked old key is not enrolled again; the daemon is stopped, so it never sees files missing)
    out="$(cli_vm "$CLIENT_VM" enroll "$DEST_NAME" --new-key --token-file /tmp/zfsb-token-t3)"; rc=$?
    printf '%s\n' "$out" | sed 's/^/    CLI: /'
    check "(K6) enroll --new-key with the scoped --replace token exits 0 (no --url: the destination exists)" "0" "$rc"
    check_has "(K6) the CLI reports the enrollment as $K_ID" "enrolled destination '${DEST_NAME}'.*as client id ${K_ID}" "$out"
    K6_FP="$(client_fp)"
    check "(K6) the new key was promoted: no client.next is left behind" "0" "$(msh "$CLIENT_VM" "ls '$TLS_DIR' | grep -c '^client\\.next'" | tr -d '[:space:]')"
    check "(K6) the client has a NEW certificate" "different" "$([ -n "$K6_FP" ] && [ "$K6_FP" != "$A_FP" ] && echo different || echo same)"
    check "(K6) the client id is unchanged" "$K_ID" "$(client_id_now)"
    check "(K6) the server pins exactly the new certificate under $K_ID" "$K6_FP -" "$(trust_pins "$K_ID")"
    check "(K6) the token is consumed, by $K_ID with the new certificate" "consumed $K_ID $K6_FP" \
        "$(cli_jget "$SERVER_VM" 'd["state"] + " " + str(d["consumed_client_id"]) + " " + str(d["consumed_fingerprint"])' trust token show --json | tr -d '\r')"
    check "(K6) B's pin is untouched" "$B_FP -" "$(trust_pins "$K_ID_B")"
    mark_c="$(loglines "$CLIENT_VM")"
    start_daemon "$CLIENT_VM"
    if wait_server_snap "$K5_NEXT" 150; then pass "(K6) the pending snapshot $K5_NEXT reached the server with the new certificate"; else fail "(K6) $K5_NEXT never reached the server"; fi
    wait_log_vm "$CLIENT_VM" "$mark_c" "Backup complete: ${SOURCE_DS}@${K5_NEXT}" 30
    stop_daemon "$CLIENT_VM"
    check_has "(K6) it was INCREMENTAL from $K5_SNAP" "Backup complete: ${SOURCE_DS}@${K5_NEXT} \(incremental from ${K5_SNAP}\)" "$(log_since_vm "$CLIENT_VM" "$mark_c")"
    check_lacks "(K6) the refusal is not repeated: the client logs no 'does not trust'" "$K_REFUSED_RE" "$(log_since_vm "$CLIENT_VM" "$mark_c")"
    check "(K6) the server dataset is the same one (guid unchanged)" "$k5_ds_guid" "$(guid "$SERVER_VM" "$(server_ds)")"
    check "(K6) the old snapshot $K5_SNAP is the same on the server (not re-received)" "$k5_snap_guid" "$(guid "$SERVER_VM" "$(server_ds)@${K5_SNAP}")"
    check "(K6) only $K_ID's directory exists under $TARGET_DS" "2" "$(msh "$SERVER_VM" "zfs list -H -d 1 -o name '$TARGET_DS' | wc -l" | tr -d '[:space:]')"
    check "(K6) the anchor advanced to $K5_NEXT" "$K5_NEXT" "$(anchor)"

    # ── K7: identity rotate ──
    echo
    step "K7 — identity rotate: two pins (one names its predecessor) until the next cycle; that cycle is incremental and retires the old pin"
    k7_old="$(client_fp)"
    out="$(cli_vm "$CLIENT_VM" identity rotate)"; rc=$?
    printf '%s\n' "$out" | sed 's/^/    CLI: /'
    check "(K7) identity rotate exits 0" "0" "$rc"
    check_has "(K7) the table says rotated for $DEST_NAME" "${DEST_NAME} +rotated" "$out"
    K7_FP="$(client_fp)"
    check "(K7) the client certificate changed" "different" "$([ -n "$K7_FP" ] && [ "$K7_FP" != "$k7_old" ] && echo different || echo same)"
    check_has "(K7) the CLI reports old -> new" "client certificate rotated: ${k7_old} -> ${K7_FP}" "$out"
    pins="$(trust_pins "$K_ID")"
    check "(K7) before the next cycle the server holds two pins for $K_ID" "2" "$(printf '%s\n' "$pins" | grep -c .)"
    check "(K7) the successor names the old certificate as its predecessor" "yes" "$(printf '%s\n' "$pins" | grep -qx "$K7_FP $k7_old" && echo yes || echo no)"
    check "(K7) the old pin has no predecessor" "yes" "$(printf '%s\n' "$pins" | grep -qx "$k7_old -" && echo yes || echo no)"
    msh "$CLIENT_VM" "head -c 1000000 /dev/urandom >> \$(zfs get -H -o value mountpoint '$SOURCE_DS')/file1.bin"
    K7_SNAP="$(snap_now)"
    mark_c="$(loglines "$CLIENT_VM")"
    start_daemon "$CLIENT_VM"
    if wait_server_snap "$K7_SNAP" 150; then pass "(K7) the next cycle succeeded with the new certificate ($K7_SNAP on the server)"; else fail "(K7) $K7_SNAP never reached the server"; fi
    wait_log_vm "$CLIENT_VM" "$mark_c" "Backup complete: ${SOURCE_DS}@${K7_SNAP}" 30
    stop_daemon "$CLIENT_VM"
    check_has "(K7) it was INCREMENTAL from $K5_NEXT" "Backup complete: ${SOURCE_DS}@${K7_SNAP} \(incremental from ${K5_NEXT}\)" "$(log_since_vm "$CLIENT_VM" "$mark_c")"
    waited=0; until [ "$(trust_pins "$K_ID" | grep -c .)" = "1" ] || [ "$waited" -ge 20 ]; do sleep 2; waited=$((waited+2)); done
    check "(K7) the old pin is retired: exactly one pin left, the new one, no predecessor" "$K7_FP -" "$(trust_pins "$K_ID")"
    check "(K7) the server dataset is still the same one" "$k5_ds_guid" "$(guid "$SERVER_VM" "$(server_ds)")"
    check "(K7) the client id is unchanged" "$K_ID" "$(client_id_now)"

    # ── K8: import leaves the identity alone ──
    echo
    step "K8 — import of a YAML leaves identity show unchanged (and the pinned destination keeps working)"
    start_daemon "$CLIENT_VM"
    id_json_before="$(cli_out "$CLIENT_VM" identity show --json | tr -d '[:space:]')"
    write_client_config "$SERVER_IP"          # a full-replace import; the YAML carries the pin ($PIN_FP)
    id_json_after="$(cli_out "$CLIENT_VM" identity show --json | tr -d '[:space:]')"
    check_has "(K8) identity show --json is a real document (client id $K_ID, fingerprint $K7_FP)" "\"client_id\":\"${K_ID}\".*${K7_FP}" "$id_json_before"
    check "(K8) identity show is byte-identical before and after the import" "$id_json_before" "$id_json_after"
    msh "$CLIENT_VM" "head -c 500000 /dev/urandom >> \$(zfs get -H -o value mountpoint '$SOURCE_DS')/file1.bin"
    K8_SNAP="$(snap_now)"
    if wait_server_snap "$K8_SNAP" 150; then pass "(K8) after the import the destination still works ($K8_SNAP reached the server)"; else fail "(K8) $K8_SNAP never reached the server after the import"; fi

    # ── K9: set-client-id is refused while enrolled ──
    echo
    step "K9 — identity set-client-id is refused while a destination is enrolled"
    out="$(cli_vm "$CLIENT_VM" identity set-client-id zfsb-k-other)"; rc=$?
    printf '%s\n' "$out" | sed 's/^/    CLI: /'
    check "(K9) set-client-id exits 1" "1" "$rc"
    check_has "(K9) the CLI says why" "refusing to change the client id while destination\(s\) '${DEST_NAME}' are enrolled" "$out"
    check "(K9) the client id is unchanged" "$K_ID" "$(client_id_now)"

    # ── K10: an http:// destination is refused at import ──
    echo
    step "K10 — importing a config with an http:// destination is refused and changes nothing"
    put_guest_file "$CLIENT_VM" /tmp/zfsb-http.yaml <<EOF
