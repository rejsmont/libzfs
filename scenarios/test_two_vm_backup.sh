#!/usr/bin/env bash
#
# test_two_vm_backup.sh — End-to-end zfsbackup transfer reliability harness.
#
# Spins up TWO real Multipass VMs (a backup server and a client), installs ZFS and
# the zfsbackup daemon in each, creates file-backed ZFS pools, and drives the daemon
# through a set of reliability scenarios that exercise the REAL network transfer path
# (real IP, 0.0.0.0 bind, WebSocket over the Multipass bridge) — not the single-VM
# zfs-CLI routing used by the pytest suite.
#
# Same daemon binary on both VMs; the role is decided purely by config:
#   - server: remote_backup.enabled + target_dataset, api_host 0.0.0.0
#   - client: datasets[].remote + destinations pointing at the server
#
# The API is HTTPS only with mutual TLS (milestone 3). The harness enrolls the client the way an operator
# would: the server's `trust token create --json` mints a one-time token, it travels to the client as a FILE
# (`multipass transfer`), and `zfsbackup-config enroll server1 --url https://<ip>:<port> --token-file ...` pins
# the server's certificate and registers the client's. The client id is generated by `enroll` and lives in the
# client's config DB (`identity show --json`); the TLS files are in <db>.tls/ (root-owned 0750 here).
#
# Schedule is deliberately short and human-followable (seconds/minutes only):
#   client: check_interval 15s, snapshot frequency 30s, remote push 30s, prune 1m
#   server: check_interval 1m, prune 5m
#
# Scenarios: A full initial transfer, B incremental, C server-down resilience + catch-up, D client
# restart persistence, and (Phase 3, live config reload; skip with --no-big):
#   E  reload the CLIENT daemon during a large (2 GiB, throttled) send: the transfer completes, the
#      remote worker is only replaced after it, and the 60s deferral WARNING appears
#   F  reload the SERVER daemon during an inbound receive: the receive completes, the API worker is
#      only replaced after it
#   G  `kill -9` the client supervisor mid-send and start a new daemon at once: the new daemon waits
#      ("waiting for them to ...") for the surviving worker to finish, then starts
#   H  `rename dataset OLD NEW --clear-stale-props` while the client daemon RUNS (Linux, verified daemon): the
#      CLI signals it, waits for it to apply the rename, then clears OLD's org.zfsbackup:* properties
#   I  received datasets are pruned NON-recursively: the client dataset is `recursive: true`, the server's copy
#      has a child with its own long retention, and the server's pruner removes the parent's old snapshots
#      without ever taking the child's same-named ones (a recursive destroy would)
#   J  interrupted-transfer RESUME (needs a tree that has `zfs.send.resume_info` and `/stream?mode=`; skipped with
#      a warning otherwise). Runs on fresh pools after I; the client's snapshot frequency is 1d so every snapshot
#      is one the scenario takes itself:
#        J1  a throttled 400 MiB send is killed mid-stream (kill -9 of the client unit): the server keeps a
#            receive_resume_token and the client its `inflight.<dest>` pin; after a newer snapshot and a restart the
#            log shows "Resumed <ds>@<token's snap> (from ...)" and then a follow-up send to the latest snapshot in
#            the same cycle; token cleared, anchor == latest, no pin left
#        J2  stale token: interrupt again, destroy the token's TARGET snapshot, restart: WARNING "Not resuming ...
#            sending fresh", the server discards the partial state (`zfs receive -A`), the incremental succeeds
#        J3  the in-flight pin protects: with the server down and the pin set, the client's pruner (20s) takes an
#            expired control snapshot but never the pinned one; after the server returns the resume completes
#        J4  D7: a second client dataset (own pool) whose server path collides is refused with 409 at negotiate;
#            the first dataset's server copy is untouched
#   K  TLS enrollment and trust (fresh pools, own quiet config, a second client identity "B" on the client VM
#      with its own DB so cases 2-4 need no third VM):
#        K1  a client that is not enrolled is refused: no client id ("remote backup skipped: no client id"), then
#            an id but no pinned server ("destination server1 is not enrolled"): nothing is sent, nothing is
#            created on the server, no request reaches /backup/
#        K2  enroll A with a token (sends the baseline); the CONSUMED token is refused for B (exit 1)
#        K3  an UNSCOPED token naming an id the server knows is refused with 409 client_id_taken (exit 1 + the
#            `--client-id` hint) and the token stays usable: B then enrolls under its own id with it
#        K4  cert B cannot reach A's data: B's certificate on A's URL gets 403 "client_id mismatch" (and no
#            certificate gets 401); A's server copy is untouched
#        K5  A's fingerprint is revoked while a (throttled) stream is in flight: the stream completes, the next
#            cycle is refused (one ERROR "does not trust this client"), nothing more is sent
#        K6  re-enroll with `trust token create --client-id A --replace` and a NEW certificate: same client id,
#            same server dataset, the pending snapshot goes out INCREMENTALLY; one pin left
#        K7  `identity rotate`: two pins (one with a predecessor) until the next cycle, which succeeds
#            incrementally and retires the old pin (one pin, no predecessor)
#        K8  `import` of a YAML leaves `identity show` unchanged (and the destination still works)
#        K9  `identity set-client-id` is refused while enrolled
#        K10 importing a config with an http:// destination is refused and changes nothing
#   L1 trust boundary (plan B-1, S-4, S-5; needs a tree with them, else skipped with a warning). Fresh pools. A is the real,
#      enrolled victim client (four snapshots on the server); B is an enrolled ATTACKER whose daemon is modified (a
#      sitecustomize in /opt/zfsb-evil makes it `zfs send -p` and stop re-syncing its config property). B (and the
#      harness, for what a client cannot do) plants `\n`/`\t` forged `zfs list -H` rows in org.zfsbackup:* values, trying to
#      make the server's pruner apply a keep-only-the-newest retention to A's dataset and to datasets outside the target:
#        L1a   end to end over mTLS: raw `zfs set` on B's dataset (libzfseasy refuses the same values), a full and an
#              incremental -p stream; the server holds its own LOCAL canonical values (it passes them to the receive
#              with `-o`, never `-x`), and the `received` column of config/client_id/source_dataset is "-" (asserted
#              with `zfs get -o received`: `-s received` cannot see a received value hidden under a local one); the
#              pruner runs >= 4 cycles, A and the outside datasets are identical by name and guid
#        L1b   hostile /negotiate bodies with B's certificate are 400 and write nothing; S-5: 426 without or with a wrong
#              X-Zfsbackup-Protocol; S-4: /config, /datasets, /datasets/<n>/snapshots are 404
#        L1c   forged LOCAL values planted on the server (row-forging config and client id, A's id on a dataset in B's tree,
#              B's id in A's tree, a received-only config, datasets outside the target, a sibling sharing the target's name
#              prefix) and >= 5 prune cycles: none is pruned, each is reported by ONE WARNING; a CONTROL dataset with the
#              same config legitimately in B's tree IS pruned, and the pre-fix tree (L1_BASELINE_REF, default 768cfed) is shown
#              to select A's dataset with the attacker's retention in the same state
#   B2 milestone B (B5-b chain, B-4 prune fallback; needs a tree with them, else skipped). Fresh pools, J's quiet config.
#        B2  a backlog of B2_N (6) managed snapshots built on the client while the server daemon is DOWN, with three
#            unmanaged snapshots in between (a hand-made name, a managed name with a `_suffix`, a suffixed one that is the
#            newest of all): once the server returns, the log shows ONE chain S0 -> B1 -> ... -> B6, one `zfs send -i` step
#            per snapshot in order, every managed snapshot on the server with the same guid in creation order, and the
#            unmanaged ones never sent
#        B4  six old snapshots planted on the server's received dataset, one HELD and one CLONED: the pruner destroys the
#            others (no failed batch), keeps the two with ONE WARNING each over several cycles, takes the held one after
#            `zfs release`; the cloned one stays
#   J5 (in J) resume MID-CHAIN: a chain of four, the second (big) step killed with kill -9; after the restart the token runs as
#      step 0 and the rest of the chain follows (plus a snapshot taken meanwhile); J1-J3/J5 also check the frozen send flags
#      (`-L -c`, never `-w`) on the running `zfs send` argv
#   M  encrypted datasets (S6 raw sends, R0 receive-creates-the-leaf; needs a tree with `_send_mode` and `server_copy`, else
#      skipped). Fresh pools, passphrase keyfile in the guest:
#        M1  raw: auto sends an encrypted dataset RAW (full + chain): the server copy is encrypted, keystatus=unavailable,
#            encryptionroot = the copy, guids match
#        M2  the server pruner destroys old snapshots of the copy with no key
#        M3  an interrupted raw send is resumed and the chain continues
#        M4  the client unmounts and UNLOADS the key: sends continue
#        M5  raw: false with the key unloaded: ONE ERROR, nothing sent (not even a negotiate)
#        M6  a plain server copy switched to raw: ONE ERROR with the `zfs rename` hint, nothing sent; after the operator renames the
#            copy aside the next cycle sends a full raw stream
#        M7  raw: true on an unencrypted dataset: ONE ERROR, nothing sent
#        M8  an ENCRYPTED server target receives a plain dataset (the receive creates the leaf; the copy inherits the
#            target's encryption, keystatus=available)
# H, I and J need a real pool but little space (J: ~1.2 GiB per VM); they run after E-G, and also with --no-big.
# E-G throttle the client's egress with `tc` (tbf) so a send lasts long enough to act on; the
# throttle is always removed again (also on error). They write ~3 GiB per VM: the VMs need ~10G disk
# (`multipass set local.<vm>.disk=10G` while stopped; VM_DISK=10G for a new VM).
#
# Usage:
#   ./scenarios/test_two_vm_backup.sh            # run all scenarios; reuse VMs; recreate pools
#   ./scenarios/test_two_vm_backup.sh --keep     # leave daemons + pools running for inspection
#   ./scenarios/test_two_vm_backup.sh --keep-pools
#   ./scenarios/test_two_vm_backup.sh --no-big   # scenarios A-D only (skip the slow E-G)
#   ./scenarios/test_two_vm_backup.sh --only-j   # provision, then only scenario J (fresh pools of its own)
#   ./scenarios/test_two_vm_backup.sh --only-k   # provision, then only scenario K (fresh pools of its own)
#   ./scenarios/test_two_vm_backup.sh --no-k     # everything except scenario K
#   ./scenarios/test_two_vm_backup.sh --only-l1  # provision, then only scenario L1 (fresh pools of its own)
#   ./scenarios/test_two_vm_backup.sh --no-l1    # everything except scenario L1
#   ./scenarios/test_two_vm_backup.sh --only-m   # provision, then only scenario M (several --only-X flags combine)
#   ./scenarios/test_two_vm_backup.sh --no-m     # everything except scenario M
#   ./scenarios/test_two_vm_backup.sh --only-b2  # provision, then only scenario B2 (backlog chain + B-4 prune fallback)
#   ./scenarios/test_two_vm_backup.sh --no-b2    # everything except scenario B2     (--no-j: everything except J)
#   ./scenarios/test_two_vm_backup.sh --purge    # delete the two VMs (and only those) at the end
#   SRC_REF=<commit-ish> ./scenarios/test_two_vm_backup.sh   # ship that tree instead of HEAD; SRC_REF=WORKTREE ships the
#                                                # working tree as it is, untracked files included (built from a throwaway
#                                                # index: the repo's index, stash list and refs are untouched)
#   L1_BASELINE_REF=<commit-ish>                 # the pre-fix tree scenario L1 asks "what would you prune?" (default 768cfed, before B-1 and B1-B3)
#
# Requires: multipass on the host (macOS/Linux). No sudo needed on the host.
#
# NOTE ON READINESS: the harness installs `requests` explicitly in the guests (it is declared in pyproject, but
# the guests run from a source tree, not a pip install) and binds the server API to 0.0.0.0. The API is HTTPS
# with a pinned mTLS client certificate on everything except /health and /enroll; probes with curl use -k
# because the PIN is verified by zfsbackup's own client, not by curl. Admission is by one-time token; there is
# still no rate limiting on /enroll and the server is werkzeug's development server (see
# docs/production_readiness_report.md). A green run here is not a security sign-off.

set -uo pipefail

# ─────────────────────────────── Configuration ──────────────────────────────
SERVER_VM="${SERVER_VM:-zfsb-server}"
CLIENT_VM="${CLIENT_VM:-zfsb-client}"

SERVER_POOL="${SERVER_POOL:-zbserver}"
CLIENT_POOL="${CLIENT_POOL:-zbclient}"
