    printf '%s\n' "$out" | sed 's/^/    CLI(B): /'
    check "(K3) the SAME token now enrolls B: exit 0" "0" "$rc"
    check_has "(K3) B is enrolled as $K_ID_B" "as client id ${K_ID_B}" "$out"
    check "(K3) the server now trusts two clients" "2" "$(cli_jget "$SERVER_VM" 'len(d)' trust list --json | tr -d '[:space:]')"
    check "(K3) the token is consumed, by B" "consumed $K_ID_B" \
        "$(cli_jget "$SERVER_VM" 'd["state"] + " " + str(d["consumed_client_id"])' trust token show --json | tr -d '\r')"
    B_FP="$(cli_jget_db "$CLIENT_VM" "$K_DB_B" 'd["client_certificate"]["fingerprint"]' identity show --json | tr -d '[:space:]')"
    check "(K3) B's certificate differs from A's" "different" "$([ -n "$B_FP" ] && [ "$B_FP" != "$A_FP" ] && echo different || echo same)"
    check "(K3) the server pins B's certificate under $K_ID_B" "$B_FP -" "$(trust_pins "$K_ID_B")"

    # ── K4: cert B cannot reach A's data ──
    echo
    step "K4 — certificate B cannot reach A's data (403 client_id mismatch); no certificate gets 401"
    A_BASE="${TLS_DIR}/client"; B_BASE="${K_TLS_B}/client"
    data_before="$(msh "$SERVER_VM" "zfs list -H -t all -o name,guid -r '$(server_ds)' | sort" | tr '\n' ' ')"
    code="$(probe "$B_BASE" GET /whoami)"
    check "(K4) control: B's certificate is accepted on /whoami (HTTP 200)" "200" "$code"
    check_has "(K4) ... and the server binds it to $K_ID_B" "\"client_id\": *\"${K_ID_B}\"" "$(probe_body)"
