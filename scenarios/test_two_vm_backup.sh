    sleep 20
    k_nothing_sent "K1b" "$mark_c" "$mark_s"
    check "(K1b) the ERROR was logged exactly once" "1" "$(log_since_vm "$CLIENT_VM" "$mark_c" | grep -cE "ERROR.*destination ${DEST_NAME} is not enrolled")"

    # ── K2: enroll A; the consumed token is refused for B ──
    echo
