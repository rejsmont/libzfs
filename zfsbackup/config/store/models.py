"""SQLAlchemy 2.0 declarative ORM models for the zfsbackup config store.

Mirrors the dataclass model in `zfsbackup/config/model.py` as it stands after
items 2b (retention keep_for/age uniqueness), 3b (per-destination retention
overrides), and the item-3 review pass (retention overrides scoped by
`dataset_remote_id` rather than a bare `destination_name`; see below). This
module defines schema only -- see `zfsbackup/config/store/__init__.py` for why the
ORM layer is kept separate from the `BackupConfig`/`DatasetConfig`
dataclasses. No engine/session code lives here (that is a later item); no
mapper conversion lives here either (also a later item).

Every duration is stored as a `(*_seconds, *_literal)` pair: the seconds
value is what the retention/scheduling algorithms compare and sort on, and
the literal is what makes a YAML round-trip preserve a user's original text
(``"30d"`` rather than rewriting it to the numerically-identical ``"1M"``).
Most `*_literal` columns are nullable: `Duration.literal` is `Optional[str]`
(it is `None` for sub-second values, which have no representable literal in
`config/model.py`'s grammar -- see `Duration._synthesize`/`.literal`), and a plain
`timedelta` has no `.literal` at all. A NULL `*_literal` means "no literal on
record; re-synthesize a best-effort one from `*_seconds` on read" rather than
an error -- synthesis is deterministic (`Duration._synthesize`), so nothing
is lost, and this is strictly more forgiving than raising for a value the
domain model itself considers legal. (In practice sub-second durations
cannot reach the DB via YAML, since `config/model.py`'s grammar is integer-only,
but `DatasetConfig.from_property` can decode one from a wire float, so the
model tolerates it here too.)

`GlobalSettings.prune_interval_seconds` is the one column where a NULL
`*_seconds` value is legal, and it means something entirely different from a
NULL `*_literal`: `config/model.py`'s `BackupConfig.prune_interval` is `None`
when absent from YAML ("follow `check_interval`"), and
`BackupConfig.effective_prune_interval` resolves that fallback lazily, on
each access, in whatever process calls it -- not once at load time --
because which process's `check_interval` should "win" is not a question a
stored value can answer. NULL `prune_interval_seconds` therefore means
"derive at read time", not "no literal on record"; see `mapper.py`. No
other `*_seconds` column is nullable for this reason: `check_interval` has
a fixed default with nothing to derive from, and every other duration
pair's NULL `*_seconds` state is simply unpopulated (dataset-level rows,
required fields) rather than a deliberate "unset, compute elsewhere" marker.

Retention scope (see item 3's basis, `backup_manager.py`'s
`needs_prunning`): retention is a bijection between intervals (`age`) and
expiries (`keep_for`) *within a scope*, where the scope is either a dataset
(local pruning) or a single per-destination override for that dataset.
`RetentionRule.dataset_remote_id IS NULL` is the dataset-level scope (what a
destination with no override of its own inherits); a non-NULL
`dataset_remote_id` scopes a rule to that `DatasetRemote` row (one dataset,
one destination) exclusively -- see `RetentionRule`'s docstring for why this
replaced a bare `destination_name` column.

SQLite treats NULLs as distinct in ordinary UNIQUE constraints, so a plain
``UNIQUE(dataset_remote_id, age_seconds)`` does not constrain the
dataset-level (NULL) rows at all -- every NULL compares unequal to every
other NULL. The ordinary unique constraint below therefore only constrains
the non-NULL (per-destination) scope; the NULL/dataset-level scope is
constrained separately via partial unique indexes
(`sqlite_where=text("dataset_remote_id IS NULL")`).

`Base.metadata` carries an explicit `naming_convention` so every
*implicitly* named constraint (bare PKs, FKs, and `Dataset.name`'s
column-level `unique=True`) gets a deterministic, introspectable name. This
must be in place before the first Alembic revision is generated: SQLite's
`batch_alter_table` requires naming a constraint to alter it, so an
autogenerated migration built against an unnamed schema would not match a
`create_all()`-built database's (also unnamed, but *differently* unnamed --
SQLAlchemy does not guarantee stable default names) constraints.
"""

from __future__ import annotations

from typing import List, Optional

from sqlalchemy import (
    CheckConstraint,
    Float,
    ForeignKey,
    ForeignKeyConstraint,
    Index,
    MetaData,
    UniqueConstraint,
    text,
)
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column, relationship

# Standard SQLAlchemy/Alembic naming convention. Explicitly-named
# constraints/indexes elsewhere in this module keep their own names; this
# only fills in names for constraints SQLAlchemy would otherwise generate
# implicitly (primary keys, foreign keys, and `Dataset.name`'s column-level
# `unique=True`).
NAMING_CONVENTION = {
    "ix": "ix_%(column_0_label)s",
    "uq": "uq_%(table_name)s_%(column_0_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}

# SQL fragments shared by the identity/trust tables. SQLite `GLOB` is case
# sensitive and has no repetition operator, so "64 lowercase hex" is a length
# test plus "no character outside [0-9a-f]".
#
# Both `length()` and `GLOB` stop at the first NUL of a TEXT value, so
# without `_NO_NUL` the store accepted `'a\x00b'` as a client id and
# `<64 hex>\x00junk` as a fingerprint -- values the Python grammar rejects,
# and which compare unequal to the canonical string everywhere else. The
# BLOB length counts every byte, NULs included; the TEXT length counts
# characters up to the first NUL. They are equal only for a NUL-free value
# whose characters are all single-byte, which both grammars below require
# anyway.
_NO_NUL = "length(CAST({col} AS BLOB)) = length({col})"
_HEX64 = (
    "(length({col}) = 64 AND {col} NOT GLOB '*[^0-9a-f]*' AND "
    + _NO_NUL
    + ")"
)
# The client-id grammar (TLS/mTLS plan A7), identical for `host_identity` and
# `clients`: 1-64 characters from [A-Za-z0-9._-], the FIRST of which must be
# [A-Za-z0-9]. The id becomes a ZFS dataset-name component on the server
# (`<target>/<client_id>/...`), so '/', '@', '#', spaces, '..' and a leading
# '.' (a hidden/relative path component) must never be storable. A leading '-'
# or '_' is rejected too: it passes a "not '.'" rule but libzfseasy refuses it
# as a ZFS dataset name, so `/enroll` would 400 for an id the store accepted.
_CLIENT_ID_OK = (
    "(length({col}) BETWEEN 1 AND 64 "
    "AND {col} NOT GLOB '*[^A-Za-z0-9._-]*' "
    "AND substr({col}, 1, 1) GLOB '[A-Za-z0-9]' "
    "AND " + _NO_NUL + ")"
)


class Base(DeclarativeBase):
    """Declarative base for every table in the config store."""

    metadata = MetaData(naming_convention=NAMING_CONVENTION)

    # `Mapped[float]` means `Float()` on SQLAlchemy 2.0 but `DOUBLE` on 2.1.
    # The Alembic baseline says `sa.Float()`, so on 2.1 the schema-drift check
    # (`compare_metadata`) reported every duration column as changed. Naming
    # the type here pins the metadata to the baseline on both versions, with
    # no migration and no version pin. (SQLite stores both as REAL, so
    # runtime behaviour never differed; only the declared type did.)
    type_annotation_map = {float: Float()}


class GlobalSettings(Base):
    """Single-row table mirroring `BackupConfig`'s scalar fields.

    Enforced as a singleton via `CHECK (id = 1)` on the primary key: any
    row other than `id = 1` violates the check, and a second `id = 1` row
    violates the primary key. No key/value EAV table is used here -- it
    would defeat typing (see docs/config_db_cli_plan.md item 3).

    Unlike `RemoteServer` (its structural twin below), an absent row here is
    always an error state: `BackupConfig` has no "no global settings"
    representation, so a missing row means an uninitialized or corrupted
    DB, never a deliberate `None`. See `RemoteServer`'s docstring for the
    contrasting case -- two identically-shaped singleton tables with
    opposite "row missing" semantics.
    """

    __tablename__ = "global_settings"
    __table_args__ = (
        # Short suffix, not the full "ck_..." name: the "ck" naming
        # convention's %(constraint_name)s token combines with whatever
        # name is given here, so passing the already-prefixed name would
        # double it up into "ck_global_settings_ck_global_settings_singleton".
        CheckConstraint("id = 1", name="singleton"),
        # prune_interval_seconds NULL means "derive from check_interval at
        # read time" (see the module docstring); prune_interval_literal is
        # meaningless without a seconds value to agree or disagree with, so
        # a NULL-seconds/non-NULL-literal row is an incoherent state this
        # rejects outright rather than letting the mapper guess which side
        # to trust.
        CheckConstraint(
            "prune_interval_seconds IS NOT NULL OR prune_interval_literal IS NULL",
            name="prune_literal_requires_seconds",
        ),
        # Intervals must be positive. A worker sleeps with `StopFlag.wait(
        # interval)`, which returns immediately for a timeout <= 0, so a zero
        # or negative `check_interval`/`prune_interval` is a hot loop that
        # shells out to `zfs list` per dataset as fast as the CPU allows
        # (Checkpoint A finding A5; `_duration_from_config("-5m")` happily
        # parses to -300s and "0m" to 0). `validate_config` rejects these
        # before a write; the CHECK is the backstop for a hand-edited row.
        # prune_interval_seconds NULL ("derive from check_interval") must
        # stay legal, hence the IS NULL arm.
        CheckConstraint("check_interval_seconds > 0", name="check_interval_positive"),
        CheckConstraint(
            "prune_interval_seconds IS NULL OR prune_interval_seconds > 0",
            name="prune_interval_positive",
        ),
        # A client certificate without its key (or the reverse) cannot
        # complete a handshake; reject the half-configured pair at the DB so
        # a hand-edited row fails loudly instead of at the first backup cycle.
        CheckConstraint(
            "(client_cert_file IS NULL) = (client_key_file IS NULL)",
            name="client_cert_key_together",
        ),
    )

    id: Mapped[int] = mapped_column(primary_key=True, default=1)
    # No Python-side `default=` on any non-key NOT NULL column in this module
    # (snapshot_prefix, api_host, api_port, dry_run, and the `recursive` /
    # `enabled` flags below). A `default=` makes the ORM substitute its value
    # for an explicit Python `None` at INSERT time, so a `BackupConfig`
    # carrying `enabled=None` (disabled under YAML: `[d for d in datasets if
    # d.enabled]`) was silently written as `True`, and `remote_backup:
    # {enabled: null}` -- disabled under YAML -- turned the unauthenticated
    # receive path ON after an import. The writer (`mapper.save_config`,
    # guarded by `validate_config`) must supply every value; a `None` now
    # fails loudly as `NOT NULL constraint failed` instead of being
    # "repaired" into a different behaviour. Dropping `default=` is
    # DDL-neutral (it is not a `server_default`), so no migration is implied.
    snapshot_prefix: Mapped[str]
    check_interval_seconds: Mapped[float] = mapped_column(nullable=False)
    check_interval_literal: Mapped[Optional[str]] = mapped_column(nullable=True)
    # Nullable: NULL means "derive from check_interval at read time" --
    # see the module docstring. Unlike every other *_seconds column in this
    # module, this NULL is not "unpopulated", it is a deliberate marker.
    prune_interval_seconds: Mapped[Optional[float]] = mapped_column(nullable=True)
    prune_interval_literal: Mapped[Optional[str]] = mapped_column(nullable=True)
    api_host: Mapped[str]
    api_port: Mapped[int]
    dry_run: Mapped[bool]
    # Optional operator-supplied client TLS credential paths (TLS/mTLS plan
    # M5). Both NULL = no client certificate configured; the CHECK in
    # __table_args__ makes "one of the two" unrepresentable, so a mapper never
    # has to guess which half of an mTLS pair was meant.
    #
    # This replaced `client_id_file`: the client id now lives in the
    # `host_identity` table, in the same database as the config, so there is
    # no per-process `$HOME`-dependent path to freeze (that was the bug the
    # old nullable column existed to dodge: a DB imported under `sudo`
    # pointing the daemon at `/root/.config/...`).
    client_cert_file: Mapped[Optional[str]] = mapped_column(nullable=True)
    client_key_file: Mapped[Optional[str]] = mapped_column(nullable=True)
    # Bumped by exactly 1 on every `mapper.save_config` -- `import` included,
    # so an import that lands between a CLI read and its write is a conflict
    # like any other write.
    #
    # It is a real compare-and-swap token. A writer reads the config and this
    # value in one read transaction (`mapper.load_config_snapshot`), edits,
    # and hands the value back as `save_config(..., expected_generation=N)`.
    # `save_config` compares it to the stored value inside its own `BEGIN
    # IMMEDIATE` transaction, before any DELETE, and raises `ConfigConflict`
    # on a mismatch. That is what stops a lost update: without the compare,
    # two CLI invocations that both read generation N each write N+1, the
    # second silently replacing the first's change, and the operator never
    # learns the first edit is gone. Atomicity of compare-and-write comes
    # from the write lock (`store/db.py`'s `BEGIN IMMEDIATE`), not from a
    # `WHERE generation = N` predicate -- the row is deleted and re-inserted
    # wholesale, so there is no UPDATE to predicate. A writer that did not
    # come through `db.py`'s writer engine (and so holds no write lock at its
    # first read) cannot use this compare safely.
    #
    # Also polled by the daemon (item 15.2/17) to report which generation it
    # is running and to detect "the config changed". The sequence starts at
    # 0 on the first save into an empty store and only ever increases; a
    # value is never reused, because the singleton row is replaced inside the
    # same transaction that read the old one.
    generation: Mapped[int] = mapped_column(default=0, nullable=False)

    def __repr__(self) -> str:
        return f"GlobalSettings(snapshot_prefix={self.snapshot_prefix!r}, generation={self.generation})"


class Dataset(Base):
    """One managed dataset, mirroring `DatasetConfig` minus its retention
    rules and per-destination remote config, which live in their own
    tables (`RetentionRule`, `DatasetRemote`) keyed by `dataset_id`.
    """

    __tablename__ = "datasets"
    __table_args__ = (
        # Same hot-loop reasoning as `GlobalSettings.check_interval_positive`:
        # a dataset's `frequency` is a divisor/period in `DatasetInfo`'s
        # aligned-reference-time maths and a worker interval for remote
        # backup, and <= 0 raises every cycle or spins.
        CheckConstraint("frequency_seconds > 0", name="frequency_positive"),
    )

    id: Mapped[int] = mapped_column(primary_key=True)
    name: Mapped[str] = mapped_column(unique=True, nullable=False)
    recursive: Mapped[bool]
    frequency_seconds: Mapped[float] = mapped_column(nullable=False)
    frequency_literal: Mapped[Optional[str]] = mapped_column(nullable=True)
    enabled: Mapped[bool]

    # DB already has ON DELETE CASCADE on the children's dataset_id FK, so
    # passive_deletes=True is paired with cascade="all, delete-orphan" to
    # let SQLAlchemy skip loading the children before delete and rely on the
    # DB to do the cascading. This is the correct pairing throughout this
    # module: cascade="all, delete-orphan" for genuinely dataset-owned rows
    # (deleting the row here should always delete them), passive_deletes
    # (True or "all", see below) so the DB's own FK behaviour -- not a
    # session-level SELECT+UPDATE/DELETE -- is what actually happens.
    retention_rules: Mapped[List["RetentionRule"]] = relationship(
        back_populates="dataset",
        cascade="all, delete-orphan",
        passive_deletes=True,
    )
    remotes: Mapped[List["DatasetRemote"]] = relationship(
        back_populates="dataset",
        cascade="all, delete-orphan",
        passive_deletes=True,
    )

    def __repr__(self) -> str:
        return f"Dataset(name={self.name!r})"


class Destination(Base):
    """A remote server that accepts backup streams, mirroring `Destination`
    (`config/model.py`). Keyed by name rather than a surrogate id: destination
    names are the natural key used throughout the config (dataset `remote`
    entries, `RemoteDatasetConfig.destination`, `to_property(destination)`)
    and there is no reason to invent a second identifier for them.

    Deliberately has no relationship to `RetentionRule`: per-destination
    retention overrides are scoped via `RetentionRule.dataset_remote_id`
    (see that class's docstring), so a `Destination` never owns retention
    rows directly -- it can only be reached from one via the owning
    `DatasetRemote`. Traversing from `Destination` straight to its
    "scoped" rules was exactly the item-3-review finding-1 bug (deleting a
    `Destination` after loading `dest.retention_rules` UPDATEd the orphaned
    rules' scope column to NULL -- silently promoting per-destination
    overrides to dataset-level rules instead of removing them); removing
    the relationship makes that mistake structurally unavailable rather
    than relying on remembering not to add a cascade to it.
    """

    __tablename__ = "destinations"
    __table_args__ = (
        CheckConstraint(
            "server_fingerprint IS NULL OR "
            + _HEX64.format(col="server_fingerprint"),
            name="server_fingerprint_hex",
        ),
    )

    name: Mapped[str] = mapped_column(primary_key=True)
    url: Mapped[str] = mapped_column(nullable=False)
    # Pinned SHA-256 of the server's certificate (TLS/mTLS plan M5): 64
    # lowercase hex, or NULL = not pinned. The CHECK keeps a malformed pin
    # (wrong length, uppercase, stray characters) from ever being stored: a
    # pin that can never match would look like a TLS failure at connect time
    # instead of a config error at write time.
    server_fingerprint: Mapped[Optional[str]] = mapped_column(nullable=True)

    # No ON DELETE clause on dataset_remotes.destination_name (see
    # DatasetRemote) -- a destination still referenced by a dataset's
    # remote config must not vanish out from under it. passive_deletes="all"
    # (rather than plain passive_deletes=True, which only suppresses the
    # load of *unloaded* collections and would still null out any
    # already-loaded children) makes that guard explicit: the ORM never
    # touches dataset_remotes rows on a Destination delete, in any case, so
    # the DELETE always reaches the DB and the DB's default FK behaviour
    # (RESTRICT) is what actually raises -- a real
    # "FOREIGN KEY constraint failed", not a misleading
    # "NOT NULL constraint failed" from the ORM's default null-out cascade
    # racing the FK check. Deliberate, not a side effect of omitting
    # `cascade`/`passive_deletes` -- see item-3-review finding 4.
    dataset_remotes: Mapped[List["DatasetRemote"]] = relationship(
        back_populates="destination",
        passive_deletes="all",
    )

    def __repr__(self) -> str:
        return f"Destination(name={self.name!r})"


class DatasetRemote(Base):
    """Per-destination remote backup config for one dataset, mirroring
    `RemoteDatasetConfig`. A NULL `frequency_*` pair means "inherit the
    dataset's own frequency" (`config/model.py`'s `RemoteDatasetConfig.frequency
    = None` precedent); a NULL `frequency_literal` alone (non-NULL
    `frequency_seconds`) means the sub-second "re-synthesize on read" case
    described in the module docstring -- the two NULL cases are
    distinguished by whether `frequency_seconds` is also NULL.

    `(dataset_id, destination_name)` is unique: `effective_retention_rules`
    and `RemoteBackupManager` both resolve a destination by first match, so
    a second row for the same pair would be silently-dead config rather
    than a rejected duplicate (item-3-review finding 3).

    `(dataset_id, id)` is also declared unique (trivially true, since `id`
    alone is already unique) purely so `RetentionRule` can FK to it as a
    composite parent key -- see that class's docstring for why.

    Per-destination *retention* overrides are not stored here -- they are
    `RetentionRule` rows scoped by `dataset_remote_id`, keeping both axes
    (dataset-level and per-destination) in the one retention table rather
    than duplicating the shape.
    """

    __tablename__ = "dataset_remotes"
    __table_args__ = (
        # NULL means "inherit the dataset's frequency" and stays legal; a
        # stored 0 would be falsy in `to_property` (treated as inherit there)
        # but a hot loop in `RemoteBackupWorker`, and negative is worse.
        CheckConstraint(
            "frequency_seconds IS NULL OR frequency_seconds > 0",
            name="frequency_positive",
        ),
        UniqueConstraint(
            "dataset_id", "destination_name",
            name="uq_dataset_remotes_dataset_destination",
        ),
        # Composite-FK support constraint for RetentionRule -- see that
        # class's docstring. Not a functional dedup: id is already unique.
        UniqueConstraint(
            "dataset_id", "id",
            name="uq_dataset_remotes_dataset_id_id",
        ),
    )

    id: Mapped[int] = mapped_column(primary_key=True)
    dataset_id: Mapped[int] = mapped_column(
        ForeignKey("datasets.id", ondelete="CASCADE"), nullable=False
    )
    # No ON DELETE CASCADE here (unlike retention_rules): a destination that
    # is still referenced by a dataset's remote config must be removed from
    # that config explicitly rather than have the reference silently
    # disappear out from under it. See Destination.dataset_remotes for the
    # explicit passive_deletes="all" that makes the DB's resulting RESTRICT
    # behaviour surface as the real error rather than an ORM null-out.
    destination_name: Mapped[str] = mapped_column(
        ForeignKey("destinations.name"), nullable=False
    )
    frequency_seconds: Mapped[Optional[float]] = mapped_column(nullable=True)
    frequency_literal: Mapped[Optional[str]] = mapped_column(nullable=True)
    # Send mode for this dataset x destination (`RemoteDatasetConfig.raw`).
    # NULL = auto ("raw if and only if the dataset is encrypted"), 1 = raw
    # required, 0 = never raw. Deliberately nullable with NO `default=` /
    # `server_default`: NULL is the meaningful third state, and a default
    # would silently turn "auto" into a hard True/False on insert -- a stream
    # format the server copy cannot leave without a full re-send. Existing
    # rows migrate to NULL (revision 5d2f8a60c1e4).
    raw: Mapped[Optional[bool]] = mapped_column(nullable=True)

    dataset: Mapped["Dataset"] = relationship(back_populates="remotes")
    destination: Mapped["Destination"] = relationship(back_populates="dataset_remotes")
    # RetentionRule.dataset_remote_id has ON DELETE CASCADE (via the
    # composite FK -- see RetentionRule), so this follows the same
    # cascade="all, delete-orphan" + passive_deletes=True pairing as
    # Dataset's collections: deleting a DatasetRemote always takes its
    # scoped overrides with it, and the DB does the actual cascading.
    #
    # primaryjoin is narrowed to dataset_remote_id == id only (rather than
    # letting SQLAlchemy infer it from the full composite FK, which also
    # touches dataset_id): dataset_id is already written by the
    # RetentionRule.dataset / Dataset.retention_rules relationship, and
    # letting two relationships both claim to synchronize it produces an
    # "overlapping relationship" warning. The DB-level composite FK (not
    # this relationship) is what actually enforces and cascades on
    # dataset_id -- this join is purely for ORM navigation.
    retention_rules: Mapped[List["RetentionRule"]] = relationship(
        back_populates="dataset_remote",
        primaryjoin="DatasetRemote.id == RetentionRule.dataset_remote_id",
        cascade="all, delete-orphan",
        passive_deletes=True,
    )

    def __repr__(self) -> str:
        return f"DatasetRemote(dataset_id={self.dataset_id}, destination_name={self.destination_name!r})"


class RetentionRule(Base):
    """One retention tier, mirroring `RetentionRule` (`config/model.py`), scoped
    to either a dataset (`dataset_remote_id IS NULL`, local pruning) or a
    single `DatasetRemote` row (`dataset_remote_id` set, a per-destination
    override for that one dataset+destination pairing -- see item 3b).

    Scoped by `dataset_remote_id` rather than a bare `destination_name`
    (item-3-review finding 2): a `destination_name` column FKing straight
    to `destinations.name` let an override exist with no owning
    `DatasetRemote` row at all -- a state `BackupConfig` cannot represent,
    and one where deleting a `DatasetRemote` left its scoped rules behind
    to reappear if the remote was re-added. Scoping through the
    `DatasetRemote` row instead makes an orphan override structurally
    impossible and makes remote deletion cascade correctly.

    `dataset_id` is kept as its own NOT NULL column (rather than derived
    from `dataset_remote_id`) because it must be populated for dataset-level
    rows, which have no `DatasetRemote` to derive it from. For scoped rows
    it is redundant with `dataset_remote_id`'s own dataset -- but rather
    than leave that redundancy unchecked, the composite
    `fk_retention_rules_dataset_remote` FK below ties both columns together
    against `dataset_remotes(dataset_id, id)`: SQLite does not enforce a
    multi-column FK when any of its columns is NULL ("MATCH SIMPLE"), so
    this FK is silently inert for dataset-level rows (`dataset_remote_id`
    NULL) and only engages for scoped rows, where it rejects a `dataset_id`
    that disagrees with the `DatasetRemote` row's actual dataset --
    verified directly (see the item-3-review verification notes) rather
    than assumed. It also supplies `ON DELETE CASCADE`, so a plain
    single-column FK on `dataset_remote_id` alone is unnecessary.

    Both `age` and `keep_for` are unique within a scope -- see the module
    docstring for why, and for the NULL-handling trap that requires the
    partial unique indexes below in addition to the ordinary unique
    constraints.
    """

    __tablename__ = "retention_rules"
    __table_args__ = (
        # Short suffixes -- see GlobalSettings' CheckConstraint for why.
        CheckConstraint("age_seconds > 0", name="age_positive"),
        CheckConstraint("keep_for_seconds > 0", name="keep_for_positive"),
        # Ties (dataset_id, dataset_remote_id) to the owning DatasetRemote
        # row's own (dataset_id, id) -- see the class docstring. Inert for
        # dataset-level rows (dataset_remote_id IS NULL); ON DELETE CASCADE
        # here is what cascades a DatasetRemote delete to its scoped rules.
        ForeignKeyConstraint(
            ["dataset_id", "dataset_remote_id"],
            ["dataset_remotes.dataset_id", "dataset_remotes.id"],
            ondelete="CASCADE",
            name="fk_retention_rules_dataset_remote",
        ),
        # Constrains the non-NULL (per-destination) scope only -- SQLite
        # treats every NULL dataset_remote_id as distinct from every other,
        # so these do NOT constrain dataset-level (NULL) rows. See the
        # partial indexes below for that case. dataset_id is intentionally
        # omitted here: a non-NULL dataset_remote_id already identifies a
        # single (dataset, destination) pairing on its own (and the FK
        # above guarantees dataset_id agrees with it), so including it
        # would be redundant.
        UniqueConstraint(
            "dataset_remote_id", "age_seconds",
            name="uq_retention_rules_remote_age",
        ),
        UniqueConstraint(
            "dataset_remote_id", "keep_for_seconds",
            name="uq_retention_rules_remote_keep_for",
        ),
        # Dataset-level (dataset_remote_id IS NULL) scope: one rule per age,
        # one rule per keep_for. Required in addition to the constraints
        # above -- see the module docstring.
        Index(
            "uq_retention_rules_dataset_age_null_remote",
            "dataset_id", "age_seconds",
            unique=True,
            sqlite_where=text("dataset_remote_id IS NULL"),
        ),
        Index(
            "uq_retention_rules_dataset_keep_for_null_remote",
            "dataset_id", "keep_for_seconds",
            unique=True,
            sqlite_where=text("dataset_remote_id IS NULL"),
        ),
    )

    id: Mapped[int] = mapped_column(primary_key=True)
    # Plain FK to datasets.id (independent of the composite FK to
    # dataset_remotes below, which targets a different table and is only
    # engaged for scoped rows) -- always required, including for
    # dataset-level rows.
    dataset_id: Mapped[int] = mapped_column(
        ForeignKey("datasets.id", ondelete="CASCADE"), nullable=False
    )
    # NULL = dataset-level scope. Non-NULL, together with dataset_id,
    # satisfies the composite FK in __table_args__ above.
    dataset_remote_id: Mapped[Optional[int]] = mapped_column(nullable=True)
    age_seconds: Mapped[float] = mapped_column(nullable=False)
    age_literal: Mapped[Optional[str]] = mapped_column(nullable=True)
    keep_for_seconds: Mapped[float] = mapped_column(nullable=False)
    keep_for_literal: Mapped[Optional[str]] = mapped_column(nullable=True)

    dataset: Mapped["Dataset"] = relationship(back_populates="retention_rules")
    # Narrowed primaryjoin -- see DatasetRemote.retention_rules for why
    # dataset_id is deliberately left out of this relationship's join
    # condition even though it is part of the DB-level composite FK.
    dataset_remote: Mapped[Optional["DatasetRemote"]] = relationship(
        back_populates="retention_rules",
        primaryjoin="RetentionRule.dataset_remote_id == DatasetRemote.id",
    )

    def __repr__(self) -> str:
        return (
            f"RetentionRule(dataset_id={self.dataset_id}, "
            f"dataset_remote_id={self.dataset_remote_id!r}, "
            f"age_literal={self.age_literal!r}, keep_for_literal={self.keep_for_literal!r})"
        )


class RemoteServer(Base):
    """Single-row table mirroring `RemoteServerConfig` -- this daemon's
    own server-side config for accepting incoming backup streams. Singleton
    enforced the same way as `GlobalSettings`.

    Unlike `GlobalSettings` (its structural twin above), an absent row here
    is *meaningful*, not an error: it is the correct encoding of
    `BackupConfig.remote_backup = None` (a daemon that does not accept
    incoming backups at all). Two identically-shaped singleton tables with
    opposite "row missing" semantics is easy to get wrong in a mapper (item
    4) that treats "no row" as uniformly "uninitialized" -- it must special-
    case this table, not `GlobalSettings`.
    """

    __tablename__ = "remote_server"
    __table_args__ = (
        CheckConstraint("id = 1", name="singleton"),
    )

    id: Mapped[int] = mapped_column(primary_key=True, default=1)
    target_dataset: Mapped[str] = mapped_column(nullable=False)
    # No `default=`: see GlobalSettings.snapshot_prefix. A Python default of
    # True here is what turned `remote_backup.enabled: null` into an enabled
    # receive path.
    enabled: Mapped[bool]

    def __repr__(self) -> str:
        return f"RemoteServer(target_dataset={self.target_dataset!r}, enabled={self.enabled})"


# --- TLS trust and host identity (TLS/mTLS plan M5) -------------------------
#
# These tables are NOT config: `mapper.save_config` wipes and re-inserts only
# the six config tables above and must never touch these. All access goes
# through `store/trust.py`. `host_identity` is written only by the CLI, and
# every change to it bumps `GlobalSettings.generation` (so the daemon reloads).
# The trust tables (`clients`, `trusted_clients`, `revoked_fingerprints`,
# `enrollment_token`, `trust_state`) have two writers -- the CLI (`trust ...`)
# and the API worker (enroll/rotate/retire) -- and never bump the config
# generation.


class HostIdentity(Base):
    """This host's own client id (client side). One row, `CHECK id = 1`.

    No row means "no id generated yet" -- an expected state on a fresh DB, so
    unlike `GlobalSettings` an absent row is not corruption. The id is
    grammar-checked here because it becomes a path component on the server.
    """

    __tablename__ = "host_identity"
    __table_args__ = (
        CheckConstraint("id = 1", name="singleton"),
        CheckConstraint(_CLIENT_ID_OK.format(col="client_id"), name="client_id_grammar"),
    )

    id: Mapped[int] = mapped_column(primary_key=True, default=1)
    client_id: Mapped[str] = mapped_column(nullable=False)
    created_at: Mapped[float] = mapped_column(nullable=False)
    updated_at: Mapped[Optional[float]] = mapped_column(nullable=True)

    def __repr__(self) -> str:
        return f"HostIdentity(client_id={self.client_id!r})"


class Client(Base):
    """A client id known to this server (server side).

    `revoked_at` is a tombstone: a revoked id keeps its row so it cannot be
    silently re-enrolled by anyone who merely knows the name, and so the
    `trusted_clients` rows that reference it never dangle.
    """

    __tablename__ = "clients"
    __table_args__ = (
        CheckConstraint(_CLIENT_ID_OK.format(col="client_id"), name="client_id_grammar"),
    )

    client_id: Mapped[str] = mapped_column(primary_key=True)
    label: Mapped[Optional[str]] = mapped_column(nullable=True)
    created_at: Mapped[float] = mapped_column(nullable=False)
    revoked_at: Mapped[Optional[float]] = mapped_column(nullable=True)

    def __repr__(self) -> str:
        return f"Client(client_id={self.client_id!r}, revoked_at={self.revoked_at!r})"


class TrustedClient(Base):
    """One pinned client certificate (server side), keyed by its fingerprint.

    A fingerprint belongs to exactly one client id (it is the primary key),
    but one client id may hold several fingerprints (plan D3), so
    `client_id` is indexed and deliberately NOT unique: during a rotation the
    old and the successor certificate are both trusted until the successor's
    first authenticated request retires the predecessor (D4).
    """

    __tablename__ = "trusted_clients"
    __table_args__ = (
        CheckConstraint(_HEX64.format(col="fingerprint"), name="fingerprint_hex"),
        CheckConstraint(
            "enrolled_via IN ('token', 'rotate')", name="enrolled_via_known"
        ),
        # NULL = not a rotation successor; otherwise it must be a well-formed
        # fingerprint (it is compared against `fingerprint` values).
        CheckConstraint(
            "predecessor_fingerprint IS NULL OR "
            + _HEX64.format(col="predecessor_fingerprint"),
            name="predecessor_fingerprint_hex",
        ),
    )

    fingerprint: Mapped[str] = mapped_column(primary_key=True)
    client_id: Mapped[str] = mapped_column(
        ForeignKey("clients.client_id"), nullable=False, index=True
    )
    cert_pem: Mapped[str] = mapped_column(nullable=False)
    not_after: Mapped[float] = mapped_column(nullable=False)
    enrolled_at: Mapped[float] = mapped_column(nullable=False)
    enrolled_via: Mapped[str] = mapped_column(nullable=False)
    predecessor_fingerprint: Mapped[Optional[str]] = mapped_column(nullable=True)

    def __repr__(self) -> str:
        return f"TrustedClient(fingerprint={self.fingerprint[:12]!r}, client_id={self.client_id!r})"


#: Why a fingerprint stopped being trusted (`RevokedFingerprint.reason`).
#: `revoked`: `trust revoke FP`; `successor_revoked`: a rotation successor
#: unpinned along with its revoked predecessor (its trust came only from
#: proof of possession of that key; without the cascade a thief who rotated
#: a stolen key A to their own C kept C after `trust revoke A`);
#: `client_revoked`: `trust revoke --client`; `replaced`: deleted by a
#: `--replace` token's enrollment; `retired`: a rotation predecessor retired
#: on its successor's first request.
REVOCATION_REASONS = (
    "revoked", "successor_revoked", "client_revoked", "replaced", "retired",
)


class RevokedFingerprint(Base):
    """A client certificate that was once pinned and never may be again
    (server side), keyed by its fingerprint.

    Before this table, revoking DELETED the pin and kept no record, and
    `enroll_client` only asked whether a fingerprint was pinned *now*: after
    `trust revoke F` (a stolen key) the host -- or the thief -- could redeem
    any fresh token with F, under any id, and the stolen key was trusted
    again. Every path that unpins a certificate (revoke, revoke --client, a
    `--replace` enrollment, rotation retirement) now records it here in the
    same transaction, and enroll/rotate refuse a recorded fingerprint. Rows
    are never deleted (an `import` keeps them: `mapper.PRESERVED_TABLES`).

    A separate table rather than a `revoked_at` column on `trusted_clients`,
    so `trusted_clients` stays "the live pins" -- a reader that forgets a
    filter cannot trust a revoked key -- and a fingerprint can never be live
    and revoked through one row's state. The two sets are kept disjoint by
    `store/trust.py`; `read_trust` additionally filters this table out of
    the pin set as the backstop.

    `client_id` is the client the pin belonged to, for display (`trust
    list`); `clients` rows are never deleted, so the FK only rejects a bogus
    id.

    `superseded_by` is set only on a `retired` row: the rotation successor
    whose first request retired this pin. Retiring deletes the predecessor's
    pin and so clears the successor's `predecessor_fingerprint`; without
    this column nothing linked the successor to the retired key any more,
    and `trust revoke A` after a thief's `/rotate` A -> C AND one request
    with C found A merely "already revoked" and left C trusted -- the
    revoke cascade did not survive the successor's first request. `revoke_
    pin` follows this link (transitively, through retired intermediates) to
    the live successor and unpins it. Deliberately NOT a foreign key: the
    successor's `trusted_clients` row may later be deleted, and this record
    is never deleted.
    """

    __tablename__ = "revoked_fingerprints"
    __table_args__ = (
        # NUL-safe like every other fingerprint column: a `<64 hex>\x00junk`
        # value would never match the canonical fingerprint it pretends to
        # revoke, so the revocation would silently not apply.
        CheckConstraint(_HEX64.format(col="fingerprint"), name="fingerprint_hex"),
        CheckConstraint(
            "reason IN (" + ", ".join(f"'{r}'" for r in REVOCATION_REASONS) + ")",
            name="reason_known",
        ),
        # NUL-safe for the same reason as `fingerprint`: a malformed link
        # would never match the successor's pin, so revoking the retired key
        # would silently not reach it.
        CheckConstraint(
            "superseded_by IS NULL OR " + _HEX64.format(col="superseded_by"),
            name="superseded_by_hex",
        ),
    )

    fingerprint: Mapped[str] = mapped_column(primary_key=True)
    client_id: Mapped[str] = mapped_column(
        ForeignKey("clients.client_id"), nullable=False, index=True
    )
    revoked_at: Mapped[float] = mapped_column(nullable=False)
    reason: Mapped[str] = mapped_column(nullable=False)
    superseded_by: Mapped[Optional[str]] = mapped_column(nullable=True)

    def __repr__(self) -> str:
        return (
            f"RevokedFingerprint(fingerprint={self.fingerprint[:12]!r}, "
            f"client_id={self.client_id!r}, reason={self.reason!r})"
        )


class EnrollmentToken(Base):
    """The one outstanding enrollment token (server side). One row.

    Only the SHA-256 of the secret is stored, never the secret. The `consumed_*`
    columns record the redemption so a retried enroll from the same client is
    idempotent while a second client cannot redeem it.
    """

    __tablename__ = "enrollment_token"
    __table_args__ = (
        CheckConstraint("id = 1", name="singleton"),
        CheckConstraint(_HEX64.format(col="secret_sha256"), name="secret_sha256_hex"),
        CheckConstraint(
            _HEX64.format(col="server_fingerprint"), name="server_fingerprint_hex"
        ),
        CheckConstraint("expires_at > created_at", name="expiry_after_creation"),
        # `--replace` only makes sense for a named client id (it replaces that
        # id's existing pins); a replace token with no id would be ambiguous
        # about whose trust it wipes. replace -> client_id IS NOT NULL.
        CheckConstraint(
            "replace = 0 OR client_id IS NOT NULL", name="replace_requires_client_id"
        ),
        CheckConstraint(
            "consumed_fingerprint IS NULL OR "
            + _HEX64.format(col="consumed_fingerprint"),
            name="consumed_fingerprint_hex",
        ),
    )

    id: Mapped[int] = mapped_column(primary_key=True, default=1)
    secret_sha256: Mapped[str] = mapped_column(nullable=False)
    server_fingerprint: Mapped[str] = mapped_column(nullable=False)
    created_at: Mapped[float] = mapped_column(nullable=False)
    expires_at: Mapped[float] = mapped_column(nullable=False)
    client_id: Mapped[Optional[str]] = mapped_column(nullable=True)
    # server_default (DDL-visible), not a Python `default=`: see the
    # GlobalSettings note on why a Python default silently rewrites a None.
    replace: Mapped[bool] = mapped_column(nullable=False, server_default=text("0"))
    consumed_at: Mapped[Optional[float]] = mapped_column(nullable=True)
    consumed_fingerprint: Mapped[Optional[str]] = mapped_column(nullable=True)
    consumed_client_id: Mapped[Optional[str]] = mapped_column(nullable=True)

    def __repr__(self) -> str:
        return f"EnrollmentToken(client_id={self.client_id!r}, consumed_at={self.consumed_at!r})"


class TrustState(Base):
    """Monotonic trust generation (server side). One row.

    Bumped by every trust write that changes the set of pins (`store/trust.py`
    is the only writer; token-only writes do not bump it) so the API worker can
    poll one integer to notice that another process changed trust. No row
    means generation 0. Distinct from
    `GlobalSettings.generation` on purpose: a trust change must not look like
    a config change and cause a reload (plan D1-A1).
    """

    __tablename__ = "trust_state"
    __table_args__ = (
        CheckConstraint("id = 1", name="singleton"),
    )

    id: Mapped[int] = mapped_column(primary_key=True, default=1)
    generation: Mapped[int] = mapped_column(nullable=False)

    def __repr__(self) -> str:
        return f"TrustState(generation={self.generation})"
